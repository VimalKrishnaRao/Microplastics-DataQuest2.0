def predict_input(new_data, model, scaler, label_encoders):
    new_df = pd.DataFrame([new_data])

    # Encode categorical features using saved encoders
    for col, le in label_encoders.items():
        if col in new_df.columns and col != "Label":
            if new_df[col].iloc[0] in le.classes_:
                new_df[col] = le.transform(new_df[col])
            else:
                print(f"⚠️ Unseen value '{new_df[col].iloc[0]}' in column '{col}', assigning -1.")
                new_df[col] = -1

    # Scale numerics
    new_scaled = scaler.transform(new_df)

    # Predict
    y_pred = model.predict(new_scaled)
    predicted_label = label_encoders['Label'].inverse_transform(y_pred)[0]
    return predicted_label

